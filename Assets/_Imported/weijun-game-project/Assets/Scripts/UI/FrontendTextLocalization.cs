    public static bool ContainsAsciiLetter(string value)
    {
        if (string.IsNullOrEmpty(value)) return false;
        for (int i = 0; i < value.Length; i++)
        {
            char character = value[i];
            if ((character >= 'A' && character <= 'Z') || (character >= 'a' && character <= 'z')) return true;
        }
        return false;
    }

    private static string ReplaceQuantityMarker(string value)
    {
        if (string.IsNullOrEmpty(value)) return value ?? string.Empty;

        StringBuilder builder = null;
        for (int i = 0; i < value.Length; i++)
        {
            char character = value[i];
            bool isQuantityMarker = (character == 'x' || character == 'X')
                && i + 1 < value.Length
                && char.IsDigit(value[i + 1])
                && (i == 0 || CanPrecedeQuantityMarker(value[i - 1]));
            if (!isQuantityMarker) continue;

            if (builder == null)
            {
                builder = new StringBuilder(value.Length);
                builder.Append(value, 0, i);
            }
            builder.Append('×');
            for (int copyIndex = i + 1; copyIndex < value.Length; copyIndex++)
            {
                char next = value[copyIndex];
                bool nextMarker = (next == 'x' || next == 'X')
                    && copyIndex + 1 < value.Length
                    && char.IsDigit(value[copyIndex + 1])
                    && (copyIndex == 0 || CanPrecedeQuantityMarker(value[copyIndex - 1]));
                builder.Append(nextMarker ? '×' : next);
            }
            return builder.ToString();
        }

        return value;
    }

    private static bool CanPrecedeQuantityMarker(char previous)
    {
        if (char.IsWhiteSpace(previous) || previous == '\n' || previous == '\r') return true;
        return !((previous >= 'A' && previous <= 'Z')
            || (previous >= 'a' && previous <= 'z')
            || char.IsDigit(previous));
    }
